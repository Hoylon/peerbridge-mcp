def _preferences_path(project_root: Path) -> Path:
    return project_root.resolve() / ".peerbridge" / "ui-preferences.json"


def _atomic_write(path: Path, payload: Mapping[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.{os.getpid()}.{secrets.token_hex(8)}.tmp")
    temporary.write_text(
        json.dumps(dict(payload), ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    os.replace(temporary, path)


def default_preferences() -> dict[str, Any]:
    return {
        "schema": UI_PREFERENCES_SCHEMA,
        "locale": "zh-Hant",
        "tutorial_completed": False,
        "theme": "pixel",
    }


def load_preferences(project_root: Path) -> dict[str, Any]:
    path = _preferences_path(project_root)
    if not path.exists():
        return default_preferences()
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise LocalizationError("UI preferences are not valid JSON") from exc
    if not isinstance(payload, dict):
        raise LocalizationError("UI preferences use an unsupported schema")
    schema = payload.get("schema")
    if schema == LEGACY_UI_PREFERENCES_SCHEMA:
        if set(payload) != {"schema", "locale", "tutorial_completed"}:
            raise LocalizationError("UI preferences contain unsupported fields")
        payload = {
            "schema": UI_PREFERENCES_SCHEMA,
            "locale": payload.get("locale"),
            "tutorial_completed": payload.get("tutorial_completed"),
            "theme": "pixel",
        }
    elif schema != UI_PREFERENCES_SCHEMA:
        raise LocalizationError("UI preferences use an unsupported schema")
    if set(payload) != {"schema", "locale", "tutorial_completed", "theme"}:
        raise LocalizationError("UI preferences contain unsupported fields")
    if payload.get("locale") not in SUPPORTED_LOCALES:
        raise LocalizationError("UI preferences contain an unsupported locale")
    if not isinstance(payload.get("tutorial_completed"), bool):
        raise LocalizationError("tutorial completion must be a boolean")
    if payload.get("theme") not in SUPPORTED_THEMES:
        raise LocalizationError("UI preferences contain an unsupported theme")
    return dict(payload)


def save_preferences(
    project_root: Path,
    *,
    locale: str,
    tutorial_completed: bool,
    theme: str = "pixel",
) -> dict[str, Any]:
    if locale not in SUPPORTED_LOCALES:
        raise LocalizationError("unsupported UI locale")
    if theme not in SUPPORTED_THEMES:
        raise LocalizationError("unsupported UI theme")
    payload = {
        "schema": UI_PREFERENCES_SCHEMA,
        "locale": locale,
        "tutorial_completed": bool(tutorial_completed),
        "theme": theme,
    }
    _atomic_write(_preferences_path(project_root), payload)
    return payload


def translate(locale: str, key: str) -> str:
    selected = locale if locale in SUPPORTED_LOCALES else "en"
    if key in _CATALOG[selected]:
        return _CATALOG[selected][key]
    if key in _CATALOG["en"]:
        return _CATALOG["en"][key]
    raise LocalizationError(f"unknown UI string: {key}")
